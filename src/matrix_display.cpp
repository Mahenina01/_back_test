#include <Arduino.h>
#include <MD_MAX72xx.h>
#include "config.h"
#include "matrix_display.h"

namespace {

constexpr uint8_t TFT_CS_PIN = 15;
constexpr uint8_t TOUCH_CS_PIN = 13;
constexpr uint8_t MAX_DEVICES = 1;

constexpr uint8_t DIGIT_GLYPHS[10][8] = {
  {0x3C, 0x66, 0x6E, 0x76, 0x66, 0x66, 0x3C, 0x00},
  {0x18, 0x38, 0x18, 0x18, 0x18, 0x18, 0x7E, 0x00},
  {0x3C, 0x66, 0x06, 0x0C, 0x30, 0x60, 0x7E, 0x00},
  {0x3C, 0x66, 0x06, 0x1C, 0x06, 0x66, 0x3C, 0x00},
  {0x0C, 0x1C, 0x3C, 0x6C, 0x7E, 0x0C, 0x0C, 0x00},
  {0x7E, 0x60, 0x7C, 0x06, 0x06, 0x66, 0x3C, 0x00},
  {0x1C, 0x30, 0x60, 0x7C, 0x66, 0x66, 0x3C, 0x00},
  {0x7E, 0x06, 0x0C, 0x18, 0x30, 0x30, 0x30, 0x00},
  {0x3C, 0x66, 0x66, 0x3C, 0x66, 0x66, 0x3C, 0x00},
  {0x3C, 0x66, 0x66, 0x3E, 0x06, 0x0C, 0x38, 0x00},
};

MD_MAX72XX matrix(MD_MAX72XX::FC16_HW,
                  PIN_MATRIX_DIN, PIN_MATRIX_CLK, PIN_MATRIX_CS,
                  MAX_DEVICES);

}

namespace MatrixDisplay {

void begin() {
  digitalWrite(TFT_CS_PIN, HIGH);
  digitalWrite(TOUCH_CS_PIN, HIGH);
  matrix.begin();
  matrix.control(MD_MAX72XX::INTENSITY, 5);
  matrix.clear();
  showDigit(0);
}

void showDigit(uint8_t digit) {
  if (digit > 9) {
    Serial.println("Chiffre MAX7219 invalide (0-9 attendu).");
    return;
  }

  matrix.clear();
  for (uint8_t row = 0; row < 8; ++row) {
    matrix.setRow(0, row, DIGIT_GLYPHS[digit][row]);
  }

  Serial.print("Chiffre affiche : ");
  Serial.println(digit);
}

}
